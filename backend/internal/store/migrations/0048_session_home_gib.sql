-- 세션 홈 용량을 세션마다 따로 저장한다.
--
-- 지금까지 홈 크기는 설치 시점 전역값(GIOSK_SESSION_HOME_GIB) 하나였고, 그마저도
-- local-path 라 강제되지 않아 사실상 장식이었다. 홈이 이미지 기반이 되면서 이 숫자가
-- 실제 파일시스템 크기가 되므로, 사용자가 세션마다 정할 수 있어야 한다.
--
-- 재시작할 때 같은 크기로 다시 올려야 하니 세션 행에 남긴다. NULL 은 이 컬럼이 생기기
-- 전에 만들어진 세션이며, 그때의 전역 기본값으로 해석한다.
--
-- 물리(SSH) 임대는 노드를 통째로 빌려주는 것이라 홈 용량 개념이 없다. 그쪽은 NULL 로 둔다.
